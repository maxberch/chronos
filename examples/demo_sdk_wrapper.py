"""Demo: Zero-boilerplate agent using Chronos client wrapper.

Shows how standard calls to client.models.generate_content(...) are
automatically recorded, cached, and branchable without manual session.step calls.
"""

import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent.parent / "src"))

import chronos

# Simulated Google GenAI Client
class FakeGenAIModels:
    def generate_content(self, model: str, contents: str):
        print(f"   [Real API Network Call] Invoking remote model '{model}'...")
        class Response:
            text = f"Summary of '{contents}' generated by {model}"
        return Response()

class FakeGenAIClient:
    def __init__(self):
        self.models = FakeGenAIModels()


def main():
    db_file = "wrapper_demo.db"

    print("=" * 65)
    print("RUN 1: Standard client calls wrapped in Chronos (Live Execution)")
    print("=" * 65)
    session1 = chronos.init(name="sdk-wrapper-demo", db_path=db_file)
    client1 = session1.wrap(FakeGenAIClient())

    # Regular uninstrumented calls!
    resp1 = client1.models.generate_content(
        model="gemini-2.5-flash",
        contents="Step 1: Ingest quarterly data"
    )
    print(f"-> Response 1: {resp1.text}")

    resp2 = client1.models.generate_content(
        model="gemini-2.5-pro",
        contents="Step 2: Synthesize strategic insights"
    )
    print(f"-> Response 2: {resp2.text}")

    print("\n" + "=" * 65)
    print("RUN 2: Forking from Step 1 (Time-Travel Replay)")
    print("=" * 65)
    # Fork from Step 1's checkpoint
    step1_chk_id = session1.store.get_branch_checkpoints("main")[0].checkpoint_id
    session2 = chronos.fork(checkpoint_id=step1_chk_id, new_branch_name="alt-step2", db_path=db_file)
    client2 = session2.wrap(FakeGenAIClient())

    # Step 1 is replayed instantly (Zero network call!)
    replay_resp1 = client2.models.generate_content(
        model="gemini-2.5-flash",
        contents="Step 1: Ingest quarterly data"
    )
    print(f"-> Replayed Response 1 (Cached): {replay_resp1.text}")

    # Step 2 with new instructions triggers live network call on the new branch
    new_resp2 = client2.models.generate_content(
        model="gemini-2.5-flash",
        contents="Step 2: Generate competitor breakdown instead"
    )
    print(f"-> New Branch Response 2: {new_resp2.text}")


if __name__ == "__main__":
    main()

