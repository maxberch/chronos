"""Unit tests for Chronos SDK auto-wrapper and duck-typed responses."""

import os
import tempfile
import unittest
from chronos.tracer import ChronosSession


class MockGenAIModels:
    def __init__(self):
        self.call_count = 0

    def generate_content(self, model: str, contents: str):
        self.call_count += 1
        class MockResponse:
            text = f"Generated by {model} for '{contents}' (call #{self.call_count})"
        return MockResponse()


class MockGenAIClient:
    def __init__(self):
        self.models = MockGenAIModels()


class MockOpenAIChatCompletions:
    def __init__(self):
        self.call_count = 0

    def create(self, model: str, messages: list):
        self.call_count += 1
        class MockChoice:
            class MockMessage:
                content = f"OpenAI completion for {model} (call #{self.call_count})"
            message = MockMessage()
        class MockChatCompletion:
            choices = [MockChoice()]
        return MockChatCompletion()


class MockOpenAIClient:
    def __init__(self):
        class Chat:
            completions = MockOpenAIChatCompletions()
        self.chat = Chat()


class TestSDKWrapper(unittest.TestCase):
    def setUp(self):
        self.fd, self.temp_db = tempfile.mkstemp(suffix=".db")
        os.close(self.fd)

    def tearDown(self):
        if os.path.exists(self.temp_db):
            os.remove(self.temp_db)

    def test_wrap_genai_client(self):
        real_client = MockGenAIClient()
        session1 = ChronosSession(run_name="genai-test", db_path=self.temp_db)
        client = session1.wrap(real_client)

        # Call 1 (Live)
        res1 = client.models.generate_content(
            model="gemini-2.5-flash",
            contents="Summarize this quarter"
        )
        self.assertEqual(real_client.models.call_count, 1)
        self.assertIn("Generated by gemini-2.5-flash", res1.text)
        chk1_id = session1.parent_checkpoint_id

        # Fork and replay
        session2 = ChronosSession.fork(
            parent_checkpoint_id=chk1_id,
            new_branch_name="replay-branch",
            db_path=self.temp_db
        )
        client2 = session2.wrap(real_client)

        # Call 1 (Replay from cache)
        cached_res1 = client2.models.generate_content(
            model="gemini-2.5-flash",
            contents="Summarize this quarter"
        )
        # Verify the underlying client was NOT called again (call_count remains 1)
        self.assertEqual(real_client.models.call_count, 1)
        # Verify duck-typed attribute access works seamlessly
        self.assertEqual(cached_res1.text, res1.text)

    def test_wrap_openai_client(self):
        real_openai = MockOpenAIClient()
        session1 = ChronosSession(run_name="openai-test", db_path=self.temp_db)
        client = session1.wrap(real_openai)

        # Call 1 (Live)
        res1 = client.chat.completions.create(
            model="gpt-4o",
            messages=[{"role": "user", "content": "Hello"}]
        )
        self.assertEqual(real_openai.chat.completions.call_count, 1)
        self.assertEqual(res1.choices[0].message.content, "OpenAI completion for gpt-4o (call #1)")
        chk1_id = session1.parent_checkpoint_id

        # Replay via fork
        session2 = ChronosSession.fork(
            parent_checkpoint_id=chk1_id,
            new_branch_name="openai-replay",
            db_path=self.temp_db
        )
        client2 = session2.wrap(real_openai)

        cached_res1 = client2.chat.completions.create(
            model="gpt-4o",
            messages=[{"role": "user", "content": "Hello"}]
        )
        # Ensure cached execution: call_count is still 1!
        self.assertEqual(real_openai.chat.completions.call_count, 1)
        self.assertEqual(cached_res1.choices[0].message.content, "OpenAI completion for gpt-4o (call #1)")


if __name__ == "__main__":
    unittest.main()

